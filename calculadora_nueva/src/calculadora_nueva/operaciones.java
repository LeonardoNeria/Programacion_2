public class operaciones {
    
    void sumar(float var_x, float var_y) {
        System.out.println(var_x + var_y);
    }
    
    void restar(float var_x, float var_y) {
        System.out.println(var_x - var_y);
    }
    
    void multiplicar(float var_x, float var_y) {
        System.out.println(var_x * var_y);
    }
    
    void dividir(float var_x, float var_y) {
        System.out.println(var_x / var_y);
    }
    
}
